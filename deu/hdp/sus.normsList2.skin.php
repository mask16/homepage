            <h5>Kapitel 1 Allgemeine Bestimmungen</h5>
            <div>
              <h6>1. Zweck</h6>
              <p>Dieser Verhaltenskodex zielt darauf ab, Kriterien für die Bestimmung des Verhaltens zu definieren, damit die Mitarbeiter die ethischen Probleme, mit denen sie während der Geschäftstätigkeit konfrontiert sind, richtig verstehen können, und die erforderlichen Verfahren für die Meldung von Verstößen festzulegen.</p>
            </div>
            <div>
              <h6>2. Anwendung</h6>
              <p>Dieser Ethikkodex gilt für alle Mitarbeiter von Hyundai Welding, unabhängig davon, ob sie in Korea oder im Ausland arbeiten. Lokale Gesetze und Vorschriften werden jedoch auch für Mitarbeiter berücksichtigt, die im Ausland arbeiten.</p>
            </div>
            <div>
              <h6>3. Definition von Begriffen</h6>
              <p class="num-text"><span>1)</span>Geld und andere Wertsachen: Alle Eigentumsvorteile wie Geld, Wertpapiere, Immobilien, Waren, Unterkunft, Mitgliedschaft, Eintritt, Rabatte, Einladungen usw.</p>
              <p class="num-text"><span>2)</span>Stakeholder: Bezieht sich auf diejenigen, die in direktem oder indirektem Zusammenhang mit der Geschäftsleistung des Unternehmens stehen und einen gegenseitigen Einfluss auf die Entscheidungsfindung des Unternehmens sowie seiner Führungskräfte und Mitarbeiter haben.</p>
              <p class="num-text"><span>3)</span>Überlegener Status: Dies bedeutet, dass ein Unternehmer mit einer überlegenen Geschäftsposition als die andere Partei die Geschäftsposition nutzt, um eine vorteilhafte Position gegenüber der anderen Partei in der Geschäftsbeziehung einzunehmen.</p>
              <p class="num-text"><span>4)</span>Reporter: Bezieht sich auf eine Person, die die Tatsache meldet, sich beschwert oder meldet, dass illegale Transaktionen, illegale Aktivitäten und andere unethische Aktivitäten von Führungskräften und Mitarbeitern des Unternehmens gemäß diesen Richtlinien des Ethikkodex stattgefunden haben oder auftreten können.</p>
