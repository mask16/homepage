            <h5>Kapitel 2 Faire und ehrliche Arbeitsleistung</h5>
            <div>
              <h6>1. Verwaltung von Geschäftsinformationen und Erstellung von Geschäftsdokumenten</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter dürfen die im Zusammenhang mit ihren beruflichen Pflichten erlangten Informationen nicht für persönliche Zwecke verwenden oder an Dritte weitergeben.</p>
              <p class="num-text"><span>2)</span>Führungskräfte und Mitarbeiter handeln keine Aktien mit internen Informationen, die sie während der Arbeit erhalten haben, und geben keine nicht offengelegten wesentlichen Informationen, die den Aktienkurs beeinflussen können, ohne ordnungsgemäßen Prozess an Dritte weiter.</p>
              <p class="num-text"><span>3)</span>Führungskräfte und Mitarbeiter müssen Dokumente gemäß den Vorschriften des Unternehmens zur Vorbereitung von Dokumenten für die Arbeit vorbereiten. Wenn Fehler in Dokumenten auftreten, müssen sie diese unverzüglich dem obersten Manager melden und korrigieren.</p>
			</div>

            <div>
              <h6>2. Personalanfrage</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter dürfen ihre übergeordnete Position nicht dazu nutzen, unangemessene Anfragen zu stellen, wie z. B. die Anwerbung von Familienmitgliedern, Verwandten und Bekannten gegenüber dem Unternehmen oder Unternehmen mit Interessen.</p>
              <p class="num-text"><span>2)</span>Führungskräfte und Mitarbeiter dürfen ihre übergeordnete Position nicht dazu nutzen, das HR-Team aufzufordern, ihre Untergebenen ohne triftigen Grund einer unfairen Personalbewertung zu unterziehen.</p>
              <p class="num-text"><span>3)</span>Die Mitarbeiter dürfen keine anderen Personen bitten, Anfragen von Personal zu erfragen, das für Personalangelegenheiten zuständig ist, um das Personal wie ihre Ernennung / Beförderung / Übermittlung in unfairer Weise zu beeinflussen.</p>
              <p class="num-text"><span>4)</span>Führungskräfte und Mitarbeiter dürfen sich nicht daran beteiligen, nach der Pensionierung von Stakeholdern eine Beschäftigungsgarantie zu erhalten.</p>
              <p class="num-text"><span>5)</span>Wenn eine Führungskraft oder ein Mitarbeiter eine Anfrage von einer anderen Person erhält, muss sie die andere Partei darüber informieren, dass die Anfrage illegal ist, und ihre Absicht, die Anfrage abzulehnen, klar angeben.</p>
            </div>

            <div>
              <h6>3. Verbot der Überlappende Beschäftigung und gleichzeitige Beschäftigung</h6>
			  <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter können ohne vorherige Genehmigung des Unternehmens nicht in einem anderen Unternehmen beschäftigt werden.</p>
			  <p class="num-text"><span>2)</span>Führungskräfte und Mitarbeiter dürfen ohne Erlaubnis des Unternehmens nicht in den Pflichten anderer Unternehmen arbeiten.</p>
            </div>

            <div>
              <h6>4. Unterzeichnung eines Vertrags mit einem Partnerunternehmen</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter müssen ihre Aufgaben fair und transparent gemäß den in den einschlägigen Gesetzen und Vorschriften festgelegten Ausschreibungen, Verträgen und Vertragserfüllungen des Unternehmens erfüllen.</p>
              <p class="num-text"><span>2)</span>Bei der Auswahl eines Partnerunternehmens sollten alle Unternehmen mit rechtlichen Qualifikationen gleiche Handelsmöglichkeiten erhalten, freien Wettbewerb gewährleisten und nach einem transparenten Bewertungsverfahren auswählen.</p>
              <p class="num-text"><span>3)</span>Grundsätzlich wird eine Bestellung durch Ausschreibung aufgegeben, es ist jedoch möglich, eine Methode wie einen freiwilligen Vertrag durch ein legitimes Verfahren gemäß den Anforderungen des Unternehmens und den damit verbundenen Vorschriften zu wählen.</p>
              <p class="num-text"><span>4)</span>Führungskräfte und Mitarbeiter dürfen von Lieferanten keine wirtschaftlichen oder unwirtschaftlichen Vorteile erhalten, wenn sie ihre übergeordnete Position nutzen.</p>
              <p class="num-text"><span>5)</span>Führungskräfte und Mitarbeiter sollten die grundlegenden Verfahren der gesamten Vertragsarbeit genau kennen, damit Bau- und Dienstleistungsverträge nicht zu einem höheren Preis als dem Marktpreis abgeschlossen werden.</p>
              <p class="num-text"><span>6)</span>Die Mitarbeiter bemühen sich, einen Interessenkonflikt bei der Unterzeichnung eines Vertrags mit einem Partnerunternehmen zu vermeiden, und melden den Konflikt im Falle eines Interessenkonflikts in der Beziehung zum Unternehmen unverzüglich dem Ethikmanagementbüro.</p>
