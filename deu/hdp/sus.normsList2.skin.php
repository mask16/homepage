            <h5>Kapitel 5 Internes Informations- und Sicherheitsmanagement usw.</h5>
            <div>
              <h6>1. Interner Informationsschutz</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter müssen das physische Eigentum, die Rechte an geistigem Eigentum und die Geschäftsgeheimnisse des Unternehmens schützen und dürfen interne Informationen wie die Vertraulichkeit des Unternehmens und Informationen über Neugeschäfte nicht ohne vorherige Genehmigung des Unternehmens an Dritte weitergeben.</p>
              <p class="num-text"><span>2)</span>Führungskräfte und Mitarbeiter dürfen die Geschäftsabwicklungsbestimmungen des Unternehmens ohne vorherige Genehmigung des Unternehmens nicht nach außen weitergeben.</p>
              <p class="num-text"><span>3)</span>Das Unternehmensinformationssystem sollte nur für geschäftliche Zwecke verwendet werden und kann nicht für persönliche Zwecke oder Gewinne verwendet werden.</p>
			</div>

            <div>
              <h6>2. Sicherheitsmanagement</h6>
              <p class="num-text"><span>1)</span>Die zugehörigen Daten des Unternehmensinformationssystems dürfen nicht ohne Genehmigung gefälscht, verändert oder beschädigt werden.</p>
              <p class="num-text"><span>2)</span>Die ID und das Passwort der PC-Kommunikation, die das Unternehmen für geschäftliche Zwecke zur Verfügung stellt, sollten nicht an andere weitergegeben werden, sofern dies jedoch vorübergehend zulässig ist, wenn dies für geschäftliche Zwecke unvermeidbar ist.</p>
              <p class="num-text"><span>3)</span>Versuchen Sie nicht, die ID und das Passwort für das Geschäft anderer herauszufinden, und verwenden Sie sie nicht, um nicht autorisierte Informationen nach dem Zufallsprinzip zu durchsuchen.</p>
              <p class="num-text"><span>4)</span>Materialien, die möglicherweise gegen das Urheberrecht verstoßen, dürfen nicht ohne Genehmigung innerhalb des Unternehmens verbreitet werden.</p>
              <p class="num-text"><span>5)</span>Führungskräfte und Mitarbeiter müssen das von ihnen offiziell erworbene Softwareprogramm verwenden. Die Verantwortung für die illegale Verwendung von Software liegt beim Mitarbeiter.</p>
