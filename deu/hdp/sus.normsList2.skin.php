            <h5>Kapitel 3 Transparente und integrale Unternehmenskultur
			</h5>
            <div>
              <h6>1. Unterschlagung und Veruntreuung öffentlicher Gelder</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter dürfen die öffentlichen Gelder des Unternehmens aus keinem Grund für persönliche Zwecke verwenden. Wenn das oben Gesagte entdeckt wird, können Strafanzeigen unter Berücksichtigung der Höhe und des Verlusts des Unternehmens eingereicht werden.</p>
              <p class="num-text"><span>2)</span>Die öffentlichen Gelder des Unternehmens müssen auf einem Unternehmenskonto verwaltet und die Ausgaben müssen gründlich dokumentiert werden.</p>
            </div>

			<div>
              <h6>2. Unsachgemäße Ausführung des Budgets</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter sollten vermeiden, das Budget aufgrund unnötiger Verwendung des Budgets oder übermäßiger Ausführung zu verschwenden, und sich bemühen, sicherzustellen, dass das Budget angemessen und effizient ausgeführt wird.</p>
              <p class="num-text"><span>2)</span>Führungskräfte und Mitarbeiter dürfen das entsprechende Budget nicht für die Geschäftsleistung mit Kunden und Stakeholdern für andere Zwecke verwenden, z. B. für Abendessen in der Abteilung, Glückwünsche und Beileid der Mitarbeiter sowie für den Kauf persönlicher Gegenstände.</p>
              <p class="num-text"><span>3)</span>Führungskräfte und Mitarbeiter dürfen die vom Unternehmen bereitgestellte Unternehmenskarte nur für Arbeitszwecke verwenden.</p>
              <p class="num-text"><span>4)</span>Führungskräfte und Mitarbeiter sollten keine Kosten geltend machen, die für andere Zwecke als die Arbeit als Unternehmenskosten verwendet werden.</p>
              <p class="num-text"><span>5)</span>Wenn ein Mitarbeiter das Budget des Unternehmens für arbeitsfreie Zwecke verwendet und es nicht dem Ethikmanagementbüro meldet, können sowohl die betroffene Person als auch der Mitarbeiter der Abteilung, denen dies bekannt ist, Disziplinarmaßnahmen ausgesetzt sein.</p>
            </div>
         <div>
              <h6>3. Private Nutzung und Beschädigung von Firmeneigentum</h6>
              <p class="num-text"><span>1)</span>Vermögenswerte des Unternehmens, wie das physische Eigentum des Unternehmens, Rechte an geistigem Eigentum und Geschäftsgeheimnisse, dürfen nicht für persönliche Zwecke verwendet werden.</p>
              <p class="num-text"><span>2)</span>Wenn ein Mitarbeiter das Vermögen des Unternehmens an sich selbst oder einen Dritten übertragen oder verleihen möchte, muss er die Genehmigung des Abteilungsleiters und der verantwortlichen Führungskraft einholen und die vorgeschriebenen Verfahren befolgen.</p>
              <p class="num-text"><span>3)</span>Mitarbeiter dürfen den Computer oder Laptop des Unternehmens nicht für den Handel mit persönlichen Aktien, Glücksspielen, illegalen Videos und anderen Websites verwenden, die nichts mit dem Geschäft zu tun haben.</p>
              <p class="num-text"><span>4)</span>Mitarbeiter dürfen das Vermögen des Unternehmens nicht absichtlich beschädigen. Wenn ein Mitarbeiter dies tut, kann das Unternehmen ihn dafür verantwortlich machen.</p>
            </div>

            <div>
              <h6>4. Annahme von Bestechung</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter fordern kein Geld, keine Waren, keine Unterhaltung, keine Bequemlichkeit usw. von den Stakeholdern, indem sie die überlegene Position in Bezug auf ihre Arbeit missbrauchen, und tätigen keine finanziellen Transaktionen zwischen Führungskräften und Mitarbeitern.</p>
              <p class="num-text"><span>2)</span>Den Mitarbeitern ist es untersagt, während Geschäftsreisen im In- und Ausland verschiedene Annehmlichkeiten im Zusammenhang mit persönlichen Geschäften wie Transportkosten, Kosten für Unterkunft und Verpflegung usw. von Interessengruppen zu erhalten. Wenn jedoch eine Bequemlichkeit unvermeidlich ist, wird diese dem Ministerium für allgemeine Angelegenheiten gemeldet und die entsprechenden Kosten werden beglichen und zurückerstattet.</p>
              <p class="num-text"><span>3)</span>Führungskräfte und Mitarbeiter dürfen keine Glückwünsche oder Glückwünsche von Stakeholdern annehmen und dürfen den interessierten Parteien die Gründe für Glückwünsche und Beileidsbekundungen nicht mitteilen, um Glückwünsche und Beileidsbekundungen oder Glückwünsche zu erhalten.</p>
			</div>
          </div>

