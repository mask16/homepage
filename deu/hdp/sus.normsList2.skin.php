            <h5>Kapitel 4 Gesunde Organisationskultur</h5>
            <div>
              <h6>1. Kapitel 4 Gesunde Organisationskultur</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Mitarbeiter müssen sich gegenseitig respektieren und die Würde mit der für das Arbeitsleben erforderlichen Höflichkeit wahren.</p>
              <p class="num-text"><span>2)</span>Führungskräfte und Mitarbeiter dürfen sich nicht aufgrund von Geschlecht, Religion, Alter, Herkunftsort, Bildung und anderen Gründen unfair diskriminieren.</p>
              <p class="num-text"><span>3)</span>Führungskräfte und Mitarbeiter dürfen sich nicht an Aktivitäten wie der Förderung von Fraktionen beteiligen, indem sie informelle Treffen innerhalb des Unternehmens bilden, ein Gefühl der Inkongruenz erzeugen oder private Interessen fördern.</p>
              <p class="num-text"><span>4)</span>Führungskräfte und Mitarbeiter dürfen Menschen mit Behinderungen nicht ohne berechtigten Grund einschränken, ausschließen, trennen oder ablehnen und dürfen in Personalangelegenheiten nicht diskriminieren.</p>
			</div>

            <div>
              <h6>2. Verantwortung der Führungskräfte und Abteilungsleiter</h6>
              <p class="num-text"><span>1)</span>Führungskräfte und Abteilungsleiter müssen den Abteilungsmitgliedern ein gutes Beispiel geben, indem sie den Ethikkodex und seine Praktiken durch faire Entscheidungen und Maßnahmen einhalten.</p>
              <p class="num-text"><span>2)</span>Führungskräfte und Abteilungsleiter beraten von Zeit zu Zeit, damit alle Abteilungsmitglieder den Ethikkodex und seine Praktiken vollständig verstehen und geeignete Vorkehrungen treffen können, um unethisches Verhalten zu verhindern.</p>
			</div>


            <div>
              <h6>3. Verantwortlichkeiten der Abteilungsmitglieder</h6>
              <p class="num-text"><span>1)</span>Wenn ein Abteilungsmitglied eine Aufgabe erledigt, die nicht in den Geschäftsabwicklungsbestimmungen des Unternehmens festgelegt oder gemäß den Vorschriften nicht klar ist, müssen sich der Abteilungsleiter und die Führungskräfte nach der Geschäftsabwicklungsmethode erkundigen und angemessen damit umgehen.</p>
              <p class="num-text"><span>2)</span>Ein Abteilungsmitglied darf die Anweisungen des Vorgesetzten nicht unbedingt befolgen, wenn es weiß, dass die Anweisungen des Vorgesetzten illegal und unfair sind.</p>
              <p class="num-text"><span>3)</span>Als Reaktion auf die unangemessene Anweisung des Vorgesetzten müssen die Untergebenen die Gründe für Ungerechtigkeit und Ablehnung vorlegen. Wenn die Ablehnung nicht korrigiert wird oder aufgrund dieser Nachteile Nachteile aufweist, muss er dies dem Ethikmanagementbüro melden.</p>

			</div>

            <div>
              <h6>4. Mobbing und sexuelle Belästigung am Arbeitsplatz</h6>
              <p>Disziplinarmaßnahmen wie Suspendierung, Abstieg, Wartezeit und Entlassung können Mitarbeitern auferlegt werden, die am Arbeitsplatz Belästigungen oder sexuelle Belästigungen verursacht haben.</p>
              <p class="num-text"><span>1)</span>Mobbing am Arbeitsplatz<br />
                - Die Mitarbeiter dürfen keine Handlungen vornehmen, die nicht mit ihren Pflichten in Zusammenhang stehen und körperliche und geistige Schmerzen verursachen oder das Arbeitsumfeld verschlechtern, indem sie ihre übergeordnete Position im Unternehmen nutzen.<br/>
                - Unnötige Arbeitsanweisungen sollten nicht vor oder nach den Geschäftszeiten erfolgen und nicht gegen die 52-Stunden-Arbeitswoche verstoßen.<br/>
                - Mitarbeiter dürfen falsche Informationen ihrer Kollegen in den sozialen Medien oder am Schwarzen Brett nicht absichtlich ausschließen oder verbreiten.<br/>
                - Manager dürfen keine vulgäre Sprache verwenden oder ihre Mitarbeiter beleidigen, auch wenn ihre Leistung schlecht ist.<br/>
                - Manager dürfen ihre Mitarbeiter nicht zwingen, an Unternehmensessen teilzunehmen, Besorgungen zu erledigen oder Berichte zu schreiben, die nichts mit der Arbeit zu tun haben.<br/>
                - Einem einzelnen Mitarbeiter darf nicht wiederholt harte Arbeit zugewiesen werden, die alle anderen Mitarbeiter nur ungern ausführen, es sei denn, dies ist in ihrem Arbeitsvertrag festgelegt.<br/>
                - Ein Mitarbeiter darf nicht ohne berechtigte Gründe absichtlich von wichtigen Informationen oder arbeitsbezogenen Entscheidungen ausgeschlossen werden.<br/>
                - Mitarbeiter dürfen von ihren Vorgesetzten nicht durch den Einsatz von Befugnissen wie Änderung, Ausschluss und Übertragung von Pflichten ungerecht behandelt werden.
			  </p>
              <p class="num-text"><span>2)</span>Sexuelle Belästigung am Arbeitsplatz<br />
                - Die Mitarbeiter dürfen keine Handlungen vornehmen, die dazu führen, dass ein Kollege sexuelle Demütigung, Ekel oder Druck verspürt.<br />
                - Den Mitarbeitern ist es untersagt, obszöne Witze, Klatsch und körperlichen Kontakt zu machen oder Menschen zu zwingen, bei Firmenessen Alkohol einzuschenken oder zu tanzen.<br />
                - Mitarbeiter dürfen sensible Körperteile eines Kollegen nicht absichtlich freilegen oder berühren oder Kollegen dazu zwingen, obszöne Fotos und Bilder zu sehen.<br />
                - Mitarbeiter dürfen die Körper oder Figuren des anderen nicht sexuell bewerten.<br />
                - Eine Ablehnung sexueller Belästigung wird respektiert, und in solchen Fällen wird kein Nachteil gewährt.<br />
                - Mitarbeiter dürfen keine Geschäfte in Bezug auf sexuelle Anforderungen machen und keine Besprechungen, romantischen Beziehungen oder körperlichen Kontakte erzwingen.
			  </p>
            </div>

            <div>
              <h6>5. Spekulatives Verhalten und Alkoholkonsum</h6>
              <p class="num-text"><span>1)</span>Mitarbeiter dürfen Kollegen nicht zum Kauf von Garantien, Finanzprodukten (Versicherungen usw.) oder anderen Waren zwingen.</p>
              <p class="num-text"><span>2)</span>Mitarbeiter dürfen keine Glücksspielaktivitäten ausüben. Wenn ein Mitarbeiter durch Glücksspiele Geld oder Wertsachen verdient, wird dies als Bestechung angesehen.</p>
              <p class="num-text"><span>3)</span>Die Mitarbeiter dürfen während der Arbeitszeit nicht von Alkohol betroffen sein. Solche Fälle werden jedoch im Falle einer vorherigen Genehmigung für das Hosting und Sponsoring von Veranstaltungen toleriert.</p>
              <p class="num-text"><span>4)</span>Mitarbeiter dürfen nicht unter Alkoholeinfluss arbeiten.</p>
              <p class="num-text"><span>5)</span>Mitarbeiter dürfen bei der Arbeit nicht unter Alkoholeinfluss fahren, und bei Feststellung können strenge Disziplinarmaßnahmen wie Entlassung getroffen werden. Wenn ein Mitarbeiter jedoch während eines Treffens mit einem Kunden unweigerlich Alkohol trinkt, kann am folgenden Tag ein Urlaub gemäß den Unternehmensbestimmungen gewährt werden. </p>
			</div>
