          <p class="num-text"><span>4.1 </span>Der Lieferant sorgt während der gesamten Produktentwicklung, Produktion, Nutzung und Entsorgung für eine saubere Umgebung.</p>
          <p class="num-text"><span>4.2 </span>Der Lieferant ergreift angemessene Maßnahmen zur Reduzierung der Treibhausgasemissionen durch Verbesserung der Energieeffizienz. </p>
          <p class="num-text"><span>4.3 </span>Der Lieferant muss die Treibhausgasemissionen verfolgen und Ziele für die Treibhausgasreduzierung im Rahmen des Pariser Klimaschutzabkommens festlegen.
​</p>

        </div>

        <div class="susCharterText">
