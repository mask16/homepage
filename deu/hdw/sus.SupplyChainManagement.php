          <p class="num-text"><span>1.1 </span>Der Lieferant führt seine Geschäftsaktivitäten fair und transparent durch und handelt in Übereinstimmung mit den Gesetzen seines jeweiligen Landes.</p>
          <p class="num-text"><span>1.2 </span>Der Lieferant muss alle geltenden internationalen Handelsnormen für alle produzierten und verkauften Produkte einhalten.</p>
