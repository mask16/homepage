        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>2. Kinderarbeit und Zwangsarbeit</b></p>
          <p class="num-text"><span>2.1 </span>Der Lieferant darf die Arbeitskraft von Kindern nicht ausbeuten und keine Personen unter 15 Jahren oder unter dem Mindestarbeitsalter beschäftigen. Personen unter 18 Jahren müssen ausnahmslos die gesetzliche Schulpflicht absolvieren. Darüber hinaus dürfen ihre Arbeitsmerkmale oder ihr Arbeitsumfeld ihre Gesundheit, Sicherheit oder Moral nicht beeinträchtigen.</p>
          <p class="num-text"><span>2.2 </span>Der Lieferant darf Arbeitnehmer nicht gegen ihren individuellen Willen zur Arbeit zwingen oder sie durch Drohung oder Nötigung zur Erbringung von Arbeit/Dienstleistung auffordern.</p>
        </div>
        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>3. Menschenrechte und Sicherheit</b></p>
          <p class="num-text"><span>3.1 </span>Der Lieferant respektiert die Mitarbeiter als unabhängige Personen und sorgt für angemessene Arbeitsbedingungen für ein sicheres Arbeitsumfeld.</p>
          <p class="num-text"><span>3.2 </span>Der Lieferant muss die erforderlichen Maßnahmen ergreifen, um ein sicheres und gesundes Arbeitsumfeld zu gewährleisten und Unfälle und Verletzungen zu verhindern, außerdem muss er die gesetzlichen Anforderungen an die Arbeitsbedingungen einhalten.</p>
          <p class="num-text"><span>3.3 </span>Der Lieferant darf Mitarbeiter nicht aufgrund von Geschlecht, Religion, Alter, Herkunft, Bildungshintergrund, Aussehen, Behinderung usw. ungerechtfertigt diskriminieren.</p>
          <p class="num-text"><span>3.4 </span>Der Lieferant muss sich darüber im Klaren sein, dass Mobbing und sexuelle Belästigung am Arbeitsplatz verboten sind, und muss ein Arbeitsumfeld schaffen, um alle Handlungen zu verhindern, die einer gesunden Beziehung zu Gleichaltrigen schaden, einschließlich körperlicher, verbaler und visueller Belästigung.</p>
		  <p class="num-text"><span>3.5 </span>Der Lieferant muss alle Unternehmensrichtlinien und -verfahren in Bezug auf Löhne und Arbeitszeiten, die auf den Gesetzen und Vorschriften des jeweiligen Landes basieren, vollständig einhalten.</p>
        </div>

