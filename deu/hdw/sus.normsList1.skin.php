              <p class="num-text"><span>1)</span>Alle Transaktionen mit unseren Kunden sind transparent und wir werden keine unfairen Handlungen oder Einflüsse durch die Nutzung der übergeordneten Position des Unternehmens auferlegen.</p>
              <p class="num-text"><span>2)</span>Allen Kunden wird eine faire Gelegenheit garantiert, und die Auswahl unserer Kunden wird durch objektive und faire Standards und Verfahren bestimmt.</p>
