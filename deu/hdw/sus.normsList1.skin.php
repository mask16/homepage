              <p class="num-text"><span>2)</span>Die Mitarbeiter geben vertrauliche Informationen nur an autorisiertes Personal weiter und dürfen keine Transaktionen zum persönlichen Vorteil durchführen, z. B. vertrauliche Informationen an Dritte weitergeben.</p>
			</div>
