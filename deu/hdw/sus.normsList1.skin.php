            <div>
              <h6>1. Grundlegende Mitarbeiterethik</h6>
              <p class="num-text"><span>1)</span>Die Mitarbeiter teilen die Managementphilosophie und die Werte des Unternehmens und führen individuell zugewiesene Aufgaben gemäß der Geschäftspolitik des Unternehmens treu aus.</p>
              <p class="num-text"><span>2)</span>Die Mitarbeiter schaffen eine Organisationskultur, die auf reibungsloser Kommunikation und gegenseitigem Vertrauen basiert.</p>
              <p class="num-text"><span>3)</span>Die Mitarbeiter dürfen nicht aus Gründen diskriminiert werden, die für ihre Pflichten irrelevant sind, wie z. B. Regionalismus, Schulbeziehungen und Verwandtschaft.</p>
              <p class="num-text"><span>4)</span>Die Mitarbeiter müssen einen Verstoß gegen die Grundsätze des ethischen Managements unverzüglich der Abteilung für ethisches Management melden.</p>
			</div>

