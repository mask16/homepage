              <p class="num-text"><span>2)</span>Mitarbeiter, die am Arbeitsplatz Belästigungen verursachen, können strengen Disziplinarmaßnahmen ausgesetzt sein, und es kann ein Personaltransfer durchgeführt werden, um zu verhindern, dass sie am selben Ort wie das Opfer arbeiten.</p>
			</div>

