              <p class="num-text"><span>2)</span>Die Mitarbeiter tragen zur Entwicklung des Unternehmens bei, indem sie ihre kreativen Fähigkeiten unter Beweis stellen.</p>
              <p class="num-text"><span>3)</span>Als Mitglieder von Hyundai Welding teilen die Mitarbeiter den Wohlstand mit dem Unternehmen und erfüllen ihre Aufgaben mit dem Willen, sich weiterzuentwickeln.</p>
              <p class="num-text"><span>4)</span>Die Mitarbeiter müssen mit den gegebenen Rechten und Pflichten vertraut sein und ethische Werte als Standard für alle Handlungen verwenden.</p>
			</div>

