            <div>
              <h6>1. Einhaltung des Gesetzes</h6>
              <p class="num-text"><span>1)</span>Wir führen Geschäftstätigkeiten fair und transparent unter Einhaltung der einschlägigen Gesetze und Vorschriften durch.</p>
