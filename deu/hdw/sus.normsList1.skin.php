              <p class="num-text"><span>2)</span>Wir erkennen an, dass unsere Mitarbeiter das Unternehmen bilden, und stellen sicher, dass alle Mitarbeiter mit Stolz als Hauptagenten der Organisation arbeiten.</p>
			</div>

            <div>
              <h6>2. Faire Behandlung und Personalentwicklung</h6>
              <p class="num-text"><span>1)</span>Wir respektieren gleichermaßen die Autonomie und Kreativität jedes Mitarbeiters und geben ihm die Möglichkeit, seine Fähigkeiten zu verbessern. Anschließend bewerten und entschädigen wir die Mitarbeiter fair nach den Bewertungskriterien.</p>
              <p class="num-text"><span>2)</span>Wir diskriminieren Mitarbeiter nicht unfair nach Geschlecht, Religion, Alter, Herkunft, Bildungshintergrund, Behinderung usw.</p>
