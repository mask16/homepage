            <div>
              <h6>2. Anwendungsbereich</h6>
              <p>
				Der Ethikkodex gilt für alle Führungskräfte und Mitarbeiter von Hyundai Welding im In- und Ausland. Führungskräfte und Mitarbeiter, die im Ausland arbeiten, müssen jedoch unter Berücksichtigung der örtlichen Gesetze und Vorschriften gelten.
			  </p>
            </div>
            <div>
              <h6>3. Anwendung des Ethikkodex</h6>
              <p class="num-text"><span>1)</span>Zur Umsetzung des Ethikkodex werden separate Richtlinien zur Umsetzung des Ethikkodex mit spezifischen Verhaltensrichtlinien erlassen.</p>
              <p class="num-text"><span>2)</span>Führungskräfte und Mitarbeiter wenden sich bei Fragen, die sich aus der Anwendung des Ethikkodex und den Richtlinien zur Umsetzung des Ethikkodex ergeben, an das Ethikmanagementbüro und befolgen dessen Interpretation.</p>
              <p class="num-text"><span>3)</span>Das Ethikmanagementbüro ändert gegebenenfalls den Ethikkodex, aber die vom Leiter des Ethikmanagementbüros als wichtig erachteten Angelegenheiten werden mit Zustimmung des Sonderausschusses für Ethik geändert.</p>
              <p class="num-text"><span>4)</span>Führungskräfte und Abteilungsleiter müssen ihre Mitarbeiter ausreichend schulen und beraten, damit sie den Kodex verstehen und geeignete Vorkehrungen treffen können, um zu verhindern, dass sie gegen den Kodex verstoßen.</p>
              <p class="num-text"><span>5)</span>Das Ethikmanagementbüro überprüft, ob es einen Bericht über einen Verstoß gegen den Ethikkodex und den Ethikkodex erhalten hat, und die zuständigen Führungskräfte und Mitarbeiter arbeiten aktiv zusammen.</p>
