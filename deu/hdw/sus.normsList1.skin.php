              <h6>3. Sichere Arbeitsumgebung</h6>
              <p class="num-text"><span>1)</span>Wir ergreifen aktiv die notwendigen Maßnahmen zur Sicherheit der Mitarbeiter und bemühen uns um ein sicheres Arbeitsumfeld vor Unfällen, Verletzungen, Katastrophen und Krankheiten.</p>
              <p class="num-text"><span>2)</span>Wir halten uns an die Gesetze und Standards in Bezug auf Gesundheit und Sicherheit am Arbeitsplatz.</p>
              <p class="num-text"><span>3)</span>Wir werden uns bemühen, ein Arbeitsumfeld zu schaffen, in dem Arbeit und Leben der Mitarbeiter harmonisch aufeinander abgestimmt sind.</p>
