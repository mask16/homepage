              <p class="num-text"><span>1)</span>Die Mitarbeiter bewahren ihre Ehre und Würde als Mitglieder von Hyundai Welding, indem sie ihre Aufgaben mit Ehrlichkeit und Integrität erfüllen.</p>
              <p class="num-text"><span>2)</span>Die Mitarbeiter müssen ihre Pflichten fair erfüllen und dürfen keine Handlungen des Missbrauchs von Autorität, Falschheit, Übertreibung usw. aus persönlichen Interessen vornehmen.</p>
              <p class="num-text"><span>3)</span>Die Mitarbeiter dürfen keine unfairen Anfragen stellen oder Gewinne von interessierten Parteien, wie z. B. Subunternehmern, als Gegenleistung für den Missbrauch des höheren Status im Geschäftsleben erzielen.</p>
              <p class="num-text"><span>4)</span>Die Mitarbeiter dürfen keinen Interessenkonflikt mit dem Unternehmen eingehen. Im Falle eines Interessenkonflikts zwischen dem Unternehmen und der Person oder Abteilung haben sie die Interessen des Unternehmens zu priorisieren.</p>
