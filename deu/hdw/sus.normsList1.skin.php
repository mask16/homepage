            <div>
              <h6>1. Zweck</h6>
              <p>
				Im Rahmen der Etablierung der Hyundai Welding Business Culture werden ethische Standards definiert, die alle Führungskräfte und Mitarbeiter einhalten müssen, und dieser Ethikkodex wird erlassen, um auf dieser Grundlage korrekte Entscheidungen zu treffen.
			  </p>
