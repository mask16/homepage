              <p class="num-text"><span>1)</span>Wir tragen zur Entwicklung der Gesellschaft und der Volkswirtschaft bei, indem wir verschiedene Gesetze einhalten, die Produktivität verbessern, Arbeitsplätze schaffen, ehrliche Steuern zahlen, Sozialbeiträge leisten usw.</p>
              <p class="num-text"><span>2)</span>Wir erkennen an, dass wir soziale Verantwortung erfüllen können, indem wir durch verschiedene soziale Aktivitäten wie Umweltschutzaktivitäten und kulturelle Unterstützungsaktivitäten zur sozialen Entwicklung beitragen.</p>
              <p class="num-text"><span>3)</span>Wir tragen zur sozialen Entwicklung bei, indem wir Unternehmensaktivitäten durchführen, die soziale Werte respektieren, und keine Aktivitäten mit unfairen Mitteln wie Bestechung für geschäftliche Vorteile und Verwertung der Gewinne von Wettbewerbern durchführen.</p>
			</div>
