              <h6>2. teigern Sie den Kundennutzen</h6>
              <p class="num-text"><span>1)</span>Wir machen faire Geschäfte mit unseren Kunden und steigern deren Gewinn. Wir betreiben keine Aktivitäten, die ihre Interessen untergraben könnten, indem sie unseren Status im Handel missbrauchen.</p>
              <p class="num-text"><span>2)</span>Wir stellen unseren Kunden ordnungsgemäße Informationen über unsere Produkte und Dienstleistungen zur Verfügung und betreiben keine irreführende  Werbung.</p>
			</div>
            <div>
              <h6>3. Kundeninformationen und Sicherheitsschutz</h6>
              <p class="num-text"><span>1)</span>Wir halten die einschlägigen Gesetze und Vorschriften zum Schutz der Kundendaten ein und verwenden oder verlieren ihre vertraulichen Informationen nicht illegal.</p>
              <p class="num-text"><span>2)</span>Bei der Bereitstellung von Produkten und Dienstleistungen für unsere Kunden betrachten wir deren Sicherheit als oberste Priorität und stellen aktiv die erforderlichen Informationen zur Verfügung, um Schäden und Risiken zu vermeiden.</p>
