        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>1. Legal Compliance</b></p>
          <p class="num-text"><span>1.1 </span>Supplier shall conduct business activities in a fair and transparent manner and operate in compliance with the laws of the applicable jurisdictions.</p>
          <p class="num-text"><span>1.2 </span>Supplier shall comply with all applicable international trade standards governing the products it manufactures and sells.</p>
