        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>2. Prohibition of Child Labor and Forced Labor</b></p>
          <p class="num-text"><span>2.1 </span>Supplier shall prohibit child labor and shall not employ individuals under the age of 15 or below the minimum legal working age established by applicable laws. Workers under the age of 18 shall not be employed in work that interferes with compulsory education or exposes them to conditions that may harm their health, safety, or moral development.</p>
          <p class="num-text"><span>2.2 </span>Supplier shall not engage in forced labor or require employees to perform work against their will, nor shall it obtain labor or services through threats, coercion, or other forms of compulsion.</p>
