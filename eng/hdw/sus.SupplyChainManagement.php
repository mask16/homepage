          <p class="titStyle7 pb10"><b>3. Human Rights and Safety</b></p>
          <p class="num-text"><span>3.1 </span>Supplier shall provide a safe and healthy working environment and take appropriate measures to prevent workplace accidents and injuries.</p>
          <p class="num-text"><span>3.2 </span>Supplier shall respect employees as independent individuals and shall not discriminate against them on the basis of gender, religion, age, place of origin, educational background, disability or any other status.</p>
          <p class="num-text"><span>3.3 </span>Supplier shall prohibit workplace harassment and sexual harassment and shall maintain a work environment free from physical, verbal, visual, or any other form of harassment that may undermine a healthy workplace culture.</p>
          <p class="num-text"><span>3.4 </span>Supplier shall establish company policies and procedures regarding wages and working hours in accordance with the laws and regulations of the applicable jurisdictions.</p>
        </div>

        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>4. Environment</b></p>
          <p class="num-text"><span>4.1 </span>Supplier shall strive to minimize adverse environmental impacts throughout the entire product lifecycle, including development, manufacturing, use, and disposal.</p>
          <p class="num-text"><span>4.2 </span>Supplier shall monitor and measure its greenhouse gas emissions and take reasonable measures to reduce such emissions.</p>
        </div>

        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>5. Business Ethics</b></p>
          <p class="num-text"><span>5.1 </span>The Supplier shall not receive any form of bribery and shall not encourage or tolerate any third party, including Hyundai Welding, engaging in conduct that violates domestic or international anti-corruption laws and related regulations.</p>
          <p class="num-text"><span>5.2 </span>Supplier shall establish internal processes for reporting unethical conduct and shall strive to foster an ethical organizational culture.</p>
          <p class="num-text"><span>5.3 </span>Supplier shall comply with all obligations relating to the protection, collection, and handling of confidential information and personal data.</p>
          <p class="num-text"><span>5.4 </span>Supplier shall ensure that business judgments remain independent and free from biased opinions or conflicts of interest.</p>
        </div>

