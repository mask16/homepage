            <h5>Chapter 2 : Fair and Truthful Performance of Duties</h5>
            <div>
              <h6>1. Management of business information and creation of documents</h6>
              <p class="num-text"><span>1)</span>Employees shall not use information acquired in the company for personal profit or disclose it to third parties.</p>
              <p class="num-text"><span>2)</span>Employees must not trade shares using internal information and must not provide confidential information to third parties that may affect stock prices without due process.</p>
              <p class="num-text"><span>3)</span>Employees shall prepare documents for business in accordance with the company's regulations, and must immediately report and modify documents in case of error.</p>
            </div>

            <div>
              <h6>2. Prohibition of request for job position</h6>
              <p class="num-text"><span>1)</span>Employees shall not make unreasonable requests to the company and its interested companies by using their status, such as asking for employment of family members, relatives, or acquaintances.</p>
              <p class="num-text"><span>2)</span>Employees must not request the HR team for unfair personnel evaluations by using their status.</p>
              <p class="num-text"><span>3)</span>Employees shall not request any other person to make a request to the HR team for an unfair influence on their appointment, promotion, transfer, etc.</p>
              <p class="num-text"><span>4)</span>Employees shall not receive any guarantee of employment after retirement from interested parties.</p>
              <p class="num-text"><span>5)</span>If an employee receives a personnel request, he/she shall inform them that it is an illegal request and clearly indicate his/her intention of refusal.</p>
            </div>

            <div>
              <h6>3. Prohibition of Multiple Jobs and Concurrent Positions</h6>
              <p class="num-text"><span>1)</span>Employees are prohibited from duplicate employment in other companies without prior approval from the company.</p>
              <p class="num-text"><span>2)</span>Employees cannot concurrently serve duties of other companies without permission from the company.</p>
            </div>

            <div>
              <h6>4. Signing Contracts with Partners</h6>
              <p class="num-text"><span>1)</span>Employees shall perform their duties fairly and transparently in accordance with the procedures prescribed by the relevant laws and regulations for bidding, contracts, and contract fulfillment conducted by the company.</p>
              <p class="num-text"><span>2)</span>When selecting a subcontractor, all duly qualified companies shall be given equal opportunity for transaction and free competition, and will be selected according to transparent evaluation procedures.</p>
              <p class="num-text"><span>3)</span>In principle, orders should be placed by competitive bidding, but private contracts may be selected through due process in accordance with the company's needs and regulations.</p>
              <p class="num-text"><span>4)</span>Employees shall not receive any form of economic or non-economic benefits from subcontractors using their superior status.</p>
              <p class="num-text"><span>5)</span>Employees shall be fully aware of the basic procedures for signing contracts and shall not conclude construction, service contracts, etc. at a higher price than the market price.</p>
              <p class="num-text"><span>6)</span>Employees shall endeavor not to have conflicting interests when signing contracts with subcontractors. In the event of a conflict of interest with the company, they shall immediately report it to the Ethics Management Department.</p>
            </div>
