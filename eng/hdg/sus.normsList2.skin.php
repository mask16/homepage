          <div class="susNormsCon susNormsCon03">
            <h5>Chapter 3 : Clean Corporate Culture</h5>
            <div>
              <h6>1. Prohibition of Embezzlement and Misappropriation of Public Funds</h6>
              <p class="num-text"><span>1)</span>Employees may not use the company's public funds for personal purposes for any reason. When detected, criminal charges may be filed according to the amount and loss.</p>
              <p class="num-text"><span>2)</span>The company's public funds shall be managed by a corporate account, and all expenditures shall be thoroughly evidenced.</p>
            </div>

            <div>
              <h6>2. Prohibition of Improper Budget Execution</h6>
              <p class="num-text"><span>1)</span>Employees shall refrain from wasting budget due to unnecessary use or excessive execution, and shall ensure that all budgets are executed reasonably and efficiently.</p>
              <p class="num-text"><span>2)</span>Employees shall not use the sales budget for purposes other than department dinners, congratulatory money for employees, and purchasing personal items.</p>
              <p class="num-text"><span>3)</span>Employees may not use corporate credit cards for any purpose that is not business related.</p>
              <p class="num-text"><span>4)</span>Employees may not charge the company expenses used for non-business purposes.</p>
              <p class="num-text"><span>5)</span>If employees use the company's budget for non-business purposes and fail to report it to the Ethics Management Department, both those involved and department employees who are aware may be subject to disciplinary action.</p>
            </div>

            <div>
              <h6>3. Prohibition of Private Use and Damage of Company Property</h6>
              <p class="num-text"><span>1)</span>Company assets, such as the company's physical property, intellectual property rights, and trade secrets, may not be used for personal purposes.</p>
              <p class="num-text"><span>2)</span>If an employee wishes to transfer or lend the company's assets to himself or a third party, they must obtain approval from the department head and the executive in charge and follow the prescribed procedures.</p>
              <p class="num-text"><span>3)</span>Employees may not use the company’s computer or laptop to engage in personal stock trading, gambling, illegal videos, and other sites unrelated to business.</p>
              <p class="num-text"><span>4)</span>Employees may not intentionally damage the company's assets. If an employee does so, the company may hold them responsible.</p>
            </div>

            <div>
              <h6>4. Prohibition of Bribery Acceptance</h6>
              <p class="num-text"><span>1)</span>Employees shall not seek any money, entertainment, or convenience from interested parties by abusing their superior positions, and shall not engage in financial transactions with colleagues.</p>
