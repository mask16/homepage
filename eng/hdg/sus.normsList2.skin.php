          <div class="susNormsCon susNormsCon04">
            <h5>Chapter 4 : Healthy Organizational Culture</h5>
            <div>
              <h6>1. Mutual Respect for Employees</h6>
              <p class="num-text"><span>1)</span>Employees should respect each other and have good manners for work life.</p>
              <p class="num-text"><span>2)</span>Employees shall not discriminate each other for reasons concerning gender, religion, age, origin, educational background, or other reasons.</p>
              <p class="num-text"><span>3)</span>Employees shall not engage in unofficial activities such as creating factions and promoting social disharmony.</p>
              <p class="num-text"><span>4)</span>Employees shall not restrict, exclude, separate, or discriminate colleagues with disabilities without justifiable reasons.</p>
            </div>

            <div>
              <h6>2. Responsibility of Executives and Department Heads</h6>
              <p class="num-text"><span>1)</span>Executives and department heads shall set a good example to department members by complying with the Code of Ethics and its practices through fair decision-making and actions.</p>
              <p class="num-text"><span>2)</span>Executives and department heads shall provide counseling from time to time so that all department members can fully understand the Code of Ethics and its practices, and take appropriate precautions to prevent unethical behavior.</p>
            </div>


            <div>
              <h6>3. Responsibility of Department Members</h6>
              <p class="num-text"><span>1)</span>When a department member is given work that is unclear under the company’s regulations, they shall ask the department head or executive before proceeding.</p>
              <p class="num-text"><span>2)</span>If a department member is given work that is illegal or unjust by their manager, they shall not proceed with it unconditionally.</p>
              <p class="num-text"><span>3)</span>A department member shall refuse unjust orders from their manager by presenting evidence. If the manager still gives unjust orders, they must be reported to the Ethics Management Department.</p>
            </div>

            <div>
              <h6>4. Prohibition of Bullying and Sexual Harassment in the Workplace</h6>
              <p>Strong disciplinary actions, such as suspension, demotion, being placed on the waiting list, dismissal, etc. may be imposed on employees who have caused bullying or sexual harassment in the workplace. Personnel transfers may also be conducted to prevent them from working in the same place as the victim.</p>
              <p class="num-text"><span>1)</span>Prohibition of Bullying<br />
                - Employees shall not engage in acts unrelated to their duties that cause physical and mental pain, or worsen the working environment by using their superior position in the company.<br />
                - No unnecessary instructions or violations shall be imposed outside of legal working hours.<br />
                - Employees shall not intentionally ostracize or spread false information of their colleagues in social media or the bulletin board.<br />
                - Managers shall not use vulgar language or insult their employees even if their performance is poor.<br />
                - Managers may not force their employees to participate in company dinners, run errands, or write reports unrelated to work.<br />
                - A single employee shall not be repeatedly assigned hard work, unless specified in their labor contract.<br/>
                - An employee shall not be intentionally excluded from important information or work related decision-making without justifiable reasons.<br/>
                - Employees shall not be treated unfairly by their managers, through the use of authority such as change, exclusion, and transfer of duties.
              </p>
              <p class="num-text"><span>2)</span>Prohibition of Sexual Harassment in the Workplace<br />
                - Employees shall not engage in any act that causes a colleague to feel sexual humiliation, disgust, or pressure.<br />
                - Employees are prohibited from making obscene jokes, gossip, physical contact, or forcing people to pour alcohol or dance in company dinners.<br />
                - Employees may not intentionally expose or touch sensitive parts of a colleague’s body, or force colleagues to see obscene photographs and pictures.<br />
                - Employees may not sexually evaluate each other’s bodies or figures.<br />
                - A refusal of sexual harassment shall be respected, and no disadvantage shall be given in such cases.<br/>
                - Employees may not make deals concerning sexual demands, and may not force meetings, romantic relationships, or physical contact.
              </p>
            </div>

            <div>
              <h6>5. Prohibition of Gambling</h6>
              <p class="num-text"><span>1)</span>Employees may not force colleagues to purchase guarantees, financial products (insurance, etc.) or other goods.</p>
              <p class="num-text"><span>2)</span>Employees shall not engage in gambling activities, and in case an employee earns money or valuables through gambling, it will be regarded as bribery.</p>
              <p class="num-text"><span>3)</span>Employees shall not be affected by alcohol during working hours. However, such cases are tolerated in case of prior approval for hosting and sponsoring events.</p>
              <p class="num-text"><span>4)</span>Employees shall not work under the influence of alcohol. Provided, that where a customer or interested party inevitably drinks at a meeting, the company may grant an alternative leave of absence the following day in accordance with the company guidelines.</p>
              <p class="num-text"><span>5)</span>Employees may not drive under the influence of alcohol for work, and strong disciplinary measures such as dismissal may be given if detected. </p>
            </div>
          </div>

          <div class="susNormsCon susNormsCon05">
            <h5>Chapter 5 : Information Protection, Security Management, etc.</h5>
            <div>
              <h6>1. Information Protection</h6>
              <p class="num-text"><span>1)</span>Employees shall protect the company's physical property, intellectual property, and business secrets. They may not divulge internal information to third parties without prior approval from the company.</p>
              <p class="num-text"><span>2)</span>Employees may not disclose the company's business regulations prior approval from the company.</p>
              <p class="num-text"><span>3)</span>The company’s information system shall be used only for business purposes and shall not be used for personal interests.</p>
            </div>

            <div>
              <h6>2. Security Management</h6>
              <p class="num-text"><span>1)</span>Data of the company's information system shall not be falsified, tampered with or damaged without permission.</p>
              <p class="num-text"><span>2)</span>The ID and password provided by the company shall not be shared with others. However, it may be temporarily shared for inevitable work purposes.</p>
              <p class="num-text"><span>3)</span>Employees are prohibited from attempting to identify other people's IDs and passwords, and unauthorized information may not be accessed.</p>
              <p class="num-text"><span>4)</span>Data that may infringe copyright may not be distributed without permission within the company.</p>
              <p class="num-text"><span>5)</span>Employees must use a purchased software program, and all responsibility for the use of illegal software shall be taken by the relevant employees.</p>
            </div>

            <div>
              <h6>3. Privacy</h6>
              <p class="num-text"><span>1)</span>Employees may not intentionally disclose personal information of employees and stakeholders.</p>
              <p class="num-text"><span>2)</span>Personal information processors must manage privacy so that it is not damaged or lost.</p>
              <p class="num-text"><span>3)</span>In order to ensure the safety of privacy, documents containing personal information and auxiliary storage media shall be stored in a locked place.</p>
              <p class="num-text"><span>4)</span>In order to prevent leakage of personal information, the company shall provide education for personal information processors.</p>
            </div>

