            <h5>第 三 章 ： 透明清廉的企业文化</h5>
            <div>
              <h6>1. 禁止贪污公款及挪用公款</h6>
			  <p class="num-text"><span>1)</span>任职员不得以任何理由将公司的公款用于私人目的。 如果发现有违规行为，可以考虑金额、公司损失等，进行刑事起诉。</p>
			  <p class="num-text"><span>2)</span>公司的公款必须用法人账户管理，对支出金要做好支出凭证。</p>

            </div>

            <div>
              <h6>2. 禁止不妥当的预算执行</h6>
				<p class="num-text"><span>1)</span>任职员工应摒弃不必要的预算使用或过多执行而浪费预算的行为，努力使预算合理、有效执行。</p>
				<p class="num-text"><span>2)</span>任职员工不得将与顾客及利害关系人进行业务执行的相关预算用于部门会餐、员工礼金及购买个人物品等非目的用途。</p>
				<p class="num-text"><span>3)</span>任职员工不得将公司支付的法人信用卡用于业务目的以外。</p>
				<p class="num-text"><span>4)</span>任职员工不得将用于业务外的经费报销为公司费用。</p>
				<p class="num-text"><span>5)</span>如果职员将公司预算用于业务外目的后，没有向伦理经营室申报，相关人员将成为惩戒对象。</p>
            </div>

            <div>
              <h6>3. 禁止公司财产私人使用及破损</h6>
				<p class="num-text"><span>1)</span>公司物质财产、知识产权、商业秘密等公司资产应用于公共用途并予以保护，不用于个人目的。</p>
				<p class="num-text"><span>2)</span>任职员工将公司资产转让或借给本人或第三者时，必须得到部门领导及负责高管的批准，并按照规定的程序进行。</p>
				<p class="num-text"><span>3)</span>不利用公司PC、笔记本电脑等进入个人股票交易、赌博、观看非法视频及登录非业务用网站，不从事与业务无关的工作。</p>
				<p class="num-text"><span>4)</span>管理人员不得有故意损坏公司资产的行为。 如果员工故意毁损公司资产，公司可以向相关员工追究责任。</p>
            </div>

            <div>
              <h6>4. 禁止收受财物等行为</h6>
				<p class="num-text"><span>1)</span>任职员工不得滥用与职务相关的优越职位，追求利益相关者的一切金钱、款待、便利等，任职员工之间不进行金钱交易。</p>
				<p class="num-text"><span>2)</span>禁止任职员工在国内外出差时，从利害关系人那里得到交通费、食宿费等有关个人公务的各种便利行为。 但是，如果不得不得到便利，则应向总务部申报，事后清算并返还相关费用。</p>
				<p class="num-text"><span>3)</span>职员不得强迫其他职员参加个人的红白喜事或送红白喜事礼金礼物。</p>
            </div>
