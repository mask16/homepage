            <h5>第 五 章 ： 公司内部信息及保安管理等</h5>
            <div>
              <h6>1. 公司内部信息保护</h6>
				<p class="num-text"><span>1)</span>任职员工应保护公司物质财产、知识产权及商业秘密，不得未经公司事先批准将公司机密及新项目相关信息等内部信息泄露给第三者。</p>
				<p class="num-text"><span>2)</span>任职员工未经公司事先批准，不得向外部泄露公司业务处理规定等。</p>
				<p class="num-text"><span>3)</span>公司信息系统只能用于业务，不能用于个人目的或利益。</p>

            </div>

            <div>
              <h6>2. 保安管理</h6>
				<p class="num-text"><span>1)</span>不得擅自伪造、变造、毁损公司信息系统相关资料。</p>
				<p class="num-text"><span>2)</span>不得与他人共享公司因业务需要提供的PC通信的ID和密码。但是，因工作原因不得已的情况，可以暂时允许。</p>
				<p class="num-text"><span>3)</span>不试图查到他人的业务ID和密码，不能利用该信息任意查阅未经许可的信息。</p>
				<p class="num-text"><span>4)</span>公司内部不得擅自发布侵犯著作权的资料。</p>
				<p class="num-text"><span>5)</span>管理人员必须使用正式购买的软件程序，因使用非法软件而造成的所有责任都由相关职员承担。</p>
            </div>

            <div>
              <h6>3. 个人信息保护</h6>
				<p class="num-text"><span>1)</span>任职员工不得向外部故意泄露任职员工、利害关系人的个人信息。</p>
				<p class="num-text"><span>2)</span>个人信息处理者应该管理个人信息，防止个人信息丢失、伪造、伪造、毁损。</p>
				<p class="num-text"><span>3)</span>为了确保个人信息的安全性，包含个人信息的文件及辅助储存媒体等应保管在有锁定装置的地方。</p>
				<p class="num-text"><span>4)</span>为了防止个人信息泄露，公司要从管理角度出发，对个人信息管理者进行教育。</p>
            </div>

