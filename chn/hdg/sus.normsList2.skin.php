				<p class="num-text"><span>1)</span>任职员工利用自己的优越地位，不向公司及有利害关系的企业提出家人、亲戚及熟人的就业请求等不当要求。</p>
				<p class="num-text"><span>2)</span>任职员工不得利用自己的优越地位，向人事业务负责人提出要求，要求下属职员在没有适当理由的情况下接受不正当的人事评价。</p>
				<p class="num-text"><span>3)</span>任职员工不得为自己的任用、晋升、转报等人事调动施加不正当影响，要求他人向人事业务负责人进行请托。</p>
				<p class="num-text"><span>4)</span>任职员工不得从利害关系人那里得到退休后就业保障的承诺。</p>
				<p class="num-text"><span>5)</span>任职员工接受他人的人事委托时，应告知对方不正当请托，并明确表明拒绝的意思。</p>
