          <div class="susNormsCon susNormsCon04">
            <h5>第 四 章 ： 健全的组织文化</h5>
            <div>
              <h6>1. 干部与职员互相尊重</h6>
			  <p class="num-text"><span>1)</span>干部与职员互相尊重，具备在职场生活所需要的基本礼仪，保持品位。</p>
			  <p class="num-text"><span>2)</span>干部与职员互相间不能以性别、宗教、年龄、出生地、学历及其他理由进行不当差别。</p>
			  <p class="num-text"><span>3)</span>干部与职员不能在公司内部建立非正式聚会，助长派系、制造抵触情绪、谋求私利等行为。</p>
			  <p class="num-text"><span>4)</span>干部与职员没有正当理由限定、排除、分离、拒绝残疾人，在人事上不能区别对待。</p>
            </div>

            <div>
              <h6>2. 干部及部门领导的责任</h6>
			  <p class="num-text"><span>1)</span>干部及部门领导通过公正的决策和行为，遵守伦理纲领和伦理纲领实践方针，作为部门职员的榜样。</p>
			  <p class="num-text"><span>2)</span>干部及部门领导应随时进行教育和商谈，以使部门职员充分了解伦理纲领及伦理杠零实践方针，并采取适当的预防措施，避免出现非伦理行为。</p>
            </div>


            <div>
              <h6>3. 部门员工的责任</h6>
				<p class="num-text"><span>1)</span>部门员工在处理内部业务处理规定没有或规定不明确的业务时，应向干部及部门领导咨询业务处理方法，公正合理处理。</p>
				<p class="num-text"><span>2)</span>部门员工明知上司的指示事项违法、不当，也不能因为是上司的指示而无条件地执行。</p>
				<p class="num-text"><span>3)</span>对于上司的不当指示，下属职员要提出不当的根据并予以拒绝，如果拒绝却未改正或因此而遭受损失的，要向伦理经营室申报。</p>
            </div>

            <div>
              <h6>4. 禁止职场内欺凌及性骚扰</h6>
              <p>对因职场内欺凌及性骚扰引起争议的职员可以给予停职、降级、待发命令及解雇等处分，同时可以同时进行人事调动，避免与受害者在同一地点工作。</p>
              <p class="num-text"><span>1)</span>禁止职场内欺凌<br />
				- 员工不得在公司中利用优越的地位，超出业务上的适当范围，给其他员工带来身体、精神上的痛苦或恶化工作环境的行为。<br />
				- 除工作时间外，不得下达不必要的指示或强行违反法定勤劳时间。<br />
				- 不得故意排挤同事职员或将歪曲事实散布到公司内部、网络及特定SNS公告栏上。<br />
				- 对业务指示事项，不因部下员工没有取得成果而进行侮辱人格、辱骂、俚语等暴力言行。<br />
				- 不强迫员工参加聚餐，也不强迫员工做与业务无关的跑腿、写报告书。<br />
				- 不得反复赋予特定员工那些在劳动合同中没有明确规定的或者其他员工都忌讳的繁重业务。<br />
				- 没有正当理由，不应在提供与业务相关的重要信息或决策过程中被排除。<br />
				- 不应利用任意变更业务、除外、推诿业务等权限，不当对待下属和同事。
              </p>
              <p class="num-text"><span>2)</span>禁止职场内性骚扰<br />
				- 员工不得做出让对方感到性屈辱感、厌恶感、压迫感等行为。<br />
				- 禁止淫秽的玩笑或淫言秽语、身体接触、聚餐时强迫饮酒或跳舞等行为。<br />
				- 不得展示淫秽照片、图片、涂鸦、淫秽出版物等行为，不得直接或通过传真或电脑发送淫秽信件、图片、图片，不得故意暴露或触摸与自己性相关的特定身体部位等行为。<br />
				- 职员之间互不进行身体的性评价或比喻。<br />
				- 要尊重拒绝性骚扰的意向或提出问题，不能以此为由给予不利。<br />
				- 不做承诺以性要求为条件给予利益，或者进行不愿意见面或强迫交往的行为，或者进行强迫身体接触的行为。
              </p>
            </div>

            <div>
              <h6>5. 禁止投机性行为等</h6>
				<p class="num-text"><span>1)</span>职员相互之间不强迫进行各种担保、金融商品（保险等）或其他物品购买的行为。</p>
				<p class="num-text"><span>2)</span>职员相互之间不进行赌博等行为，因此获得利益时视为收受金钱等行为。</p>
				<p class="num-text"><span>3)</span>任职员工在工作时间不能因饮酒而影响业务执行。 但是，为举办及赞助活动而事先得到批准的情况除外。</p>
				<p class="num-text"><span>4)</span>任职员工不得饮酒后醉酒上班并执行公司业务。</p>
				<p class="num-text"><span>5)</span>职员在执行业务时绝对不能酒后驾驶，如果发现相关事项，可以给予解雇等严厉惩罚。 但是在与顾客或利害关系人见面不可避免地饮酒时，公司可以根据公司规定在第二天给予代替休假。</p>
