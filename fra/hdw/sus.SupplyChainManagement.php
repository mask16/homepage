          <h3 class="text-style1">
			<b>
				Hyundai Welding s'engage à atteindre l'excellence en tant qu'entreprise de premier plan, en œuvrant vers la prospérité collective des parties prenantes et de la communauté selon notre vision d'entreprise, « BESCOM » (meilleure entreprise, meilleure performance de gestion et création de valeur). Pour réaliser cette vision, nous avons établi un « Code de conduite des fournisseurs » qui englobe la création d'un environnement de travail sûr, le respect des travailleurs, l'adoption de politiques respectueuses de l'environnement et la culture d'une conscience éthique.
Nous exigeons que tous les fournisseurs nationaux et étrangers de Hyundai Welding se conforment fidèlement à notre Code de conduite des fournisseurs, ainsi qu'aux lois nationales et internationales. En tant qu'entreprise mondiale, Hyundai Welding gère systématiquement les risques ESG tout au long de sa chaîne d'approvisionnement, garantissant la durabilité et des pratiques responsables à chaque étape. <br>
			</b>
		  </h3>
        </div>


        <p class="titStyle5">Code de conduite des fournisseurs Hyundai Welding</p>

        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>1. Respect des lois et réglementations </b></p>
          <p class="num-text"><span>1.1 </span>Le fournisseur doit mener ses activités commerciales de manière équitable et transparente et fonctionner conformément aux lois de leurs pays respectifs.</p>
          <p class="num-text"><span>1.2 </span>Le fournisseur doit se conformer à toutes les normes commerciales internationales applicables pour tous les produits fabriqués et vendus.</p>
        </div>

        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>2. Travail des enfants et travail forcé</b></p>
          <p class="num-text"><span>2.1 </span>Le fournisseur ne doit pas exploiter la main-d'œuvre des enfants ni employer des personnes de moins de 15 ans ou inférieures à l'âge minimum de travail. Les personnes de moins de 18 ans doivent suivre l'enseignement obligatoire prescrit par la loi, sans exception. De plus, leurs caractéristiques de travail ou leur environnement de travail ne doivent pas nuire à leur santé, leur sécurité ou leur moralité.</p>
          <p class="num-text"><span>2.2 </span> Le fournisseur ne doit pas forcer les travailleurs à travailler contre leur volonté individuelle ni leur demander de fournir un travail/un service par la menace ou la coercition.</p>
        </div>
        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>3. Droits de l'homme et sécurité</b></p>
          <p class="num-text"><span>3.1 </span>Le fournisseur doit respecter les employés en tant qu'individus indépendants et offrir des conditions de travail appropriées pour un environnement de travail sûr.</p>
          <p class="num-text"><span>3.2 </span>Le fournisseur doit prendre les mesures nécessaires pour fournir un environnement de travail sûr et sain et prévenir les accidents et les blessures, en plus de se conformer aux exigences légales en matière de conditions de travail.</p>
          <p class="num-text"><span>3.3 </span>Le fournisseur ne doit pas discriminer injustement les employés sur la base du sexe, de la religion, de l'âge, de l'origine, de la formation, de l'apparence, du handicap, etc.</p>
          <p class="num-text"><span>3.4 </span>Le fournisseur doit être conscient que l'intimidation et le harcèlement sexuel sur le lieu de travail sont interdits et doit créer un environnement de travail pour empêcher toute action susceptible de nuire à une relation saine avec ses pairs, y compris le harcèlement physique, verbal et visuel.</p>
		  <p class="num-text"><span>3.5 </span>Le fournisseur doit se conformer pleinement à toutes les politiques et procédures de l'entreprise liées aux salaires et aux heures de travail, basées sur les lois et réglementations établies par chaque pays.</p>
        </div>

        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>4. Environnement </b></p>
          <p class="num-text"><span>4.1 </span>Le fournisseur doit maintenir un environnement propre tout au long du développement, de la production, de l'utilisation et de l'élimination du produit.</p>
          <p class="num-text"><span>4.2 </span>Le fournisseur doit prendre des mesures raisonnables pour réduire les émissions de gaz à effet de serre en améliorant l'efficacité énergétique.</p>
          <p class="num-text"><span>4.3 </span>Le fournisseur devra suivre les émissions de gaz à effet de serre et fixer des objectifs de réduction des gaz à effet de serre dans le cadre de l'Accord de Paris sur le changement climatique.</p>

        </div>

        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>5. Corruption et pots-de-vin</b></p>
          <p class="num-text"><span>5.1 </span>Le fournisseur n'autorisera pas la corruption et/ou toute autre forme de corruption qui viole les réglementations en vertu des lois anti-corruption nationales et internationales.</p>
          <p class="num-text"><span>5.2 </span>Le fournisseur doit planifier un processus pour signaler les comportements contraires à l'éthique et s'efforcer de former cette culture organisationnelle.</p>
          <p class="num-text"><span>5.3 </span>Le fournisseur doit se conformer aux obligations relatives à la protection, à la collecte et au traitement approprié des informations confidentielles et personnelles.</p>
          <p class="num-text"><span>5.4 </span>Le fournisseur ne doit pas permettre que les préjugés, les préjugés, les conflits d'intérêts ou l'influence indue d'autrui l'emportent sur nos jugements professionnels ou commerciaux objectifs.</p>
        </div>
        <div class="susCharterText">
          <p class="titStyle7 pb10"><b>6. Commerce équitable </b></p>
          <p class="num-text"><span>6.1 </span>Le fournisseur doit respecter le principe de libre concurrence et veiller à ce que toutes les transactions soient équitables et transparentes.</p>
          <p class="num-text"><span>6.2 </span>Le fournisseur ne doit pas utiliser sa position supérieure pour imposer ou exercer une influence indue sur des pratiques déloyales.</p>
        </div>
