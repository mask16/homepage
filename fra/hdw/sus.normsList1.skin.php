              <p class="num-text"><span>1)</span>Les employés reconnaissent que le harcèlement général et sexuel sur le lieu de travail est illégal et ne doivent se livrer à aucun acte qui nuit aux relations avec les pairs, y compris la violence physique, verbale et visuelle.</p>
              <p class="num-text"><span>2)</span>Les employés qui causent du harcèlement sur le lieu de travail peuvent faire l'objet de mesures disciplinaires sévères et un transfert de personnel peut être effectué pour les empêcher de travailler au même endroit que la victime.</p>
            </div>

            <div>
              <h6>5. Cadeaux mutuels et transactions monétaires entre employés</h6>
              <p class="num-text"><span>1)</span>Les cadeaux entre employés doivent rester dans la norme sociale.</p>
              <p class="num-text"><span>2)</span>Tous les prêts financiers, garanties et activités de sollicitation entre employés sont interdits.</p>
            </div>

            <div>
              <h6>6. Protection des actifs et des informations de l'entreprise</h6>
              <p class="num-text"><span>1)</span>Les employés doivent protéger la propriété physique, la propriété intellectuelle, les informations commerciales, etc. de l'entreprise et ne doivent pas utiliser les actifs de l'entreprise à des fins personnelles.</p>
              <p class="num-text"><span>2)</span>Employees shall provide confidential information only to authorized personnel, and shall not make transactions for personal gain, such as providing confidential information to third parties.</p>
              <p class="num-text"><span>3)</span> Les employés doivent fournir des informations confidentielles uniquement au personnel autorisé et ne doivent pas effectuer de transactions à des fins personnelles, telles que la fourniture d'informations confidentielles à des tiers.</p>
