              <h6>2. Augmenter la valeur client</h6>
              <p class="num-text"><span>1)</span>Nous concluons des accords équitables avec nos clients et améliorons leurs profits. Nous ne nous engageons pas dans des activités susceptibles de porter atteinte à leurs intérêts en abusant de notre statut commercial.</p>
              <p class="num-text"><span>2)</span>Nous fournissons des informations précises sur nos produits et services aux clients et n'exagérons pas nos publicités.</p>
