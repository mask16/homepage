            <div>
              <h6>3. Informations client et protection de la sécurité</h6>
              <p class="num-text"><span>1)</span>Nous respectons les lois et réglementations en vigueur pour protéger les informations des clients et n'utilisons ni ne divulguons leurs informations confidentielles de manière illégale.</p>
              <p class="num-text"><span>2)</span>Dans le processus de fourniture de produits et services à nos clients, nous considérons leur sécurité comme une priorité absolue et fournissons activement les informations nécessaires pour prévenir les dommages et les risques.</p>
