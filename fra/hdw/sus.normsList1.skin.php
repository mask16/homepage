              <h6>2. Traitement équitable et développement des ressources humaines</h6>
              <p class="num-text"><span>1)</span>Nous respectons également l'autonomie et la créativité de chaque employé et leur donnons l'opportunité d'améliorer leurs capacités. Nous évaluons et rémunérons ensuite les employés équitablement conformément aux critères d'évaluation.</p>
              <p class="num-text"><span>2)</span>Nous ne discriminons pas injustement les employés en fonction du sexe, de la religion, de l'âge, de l'origine, de la formation, du handicap, etc.</p>
              <p class="num-text"><span>3)</span>Nous écoutons nos employés et créons un environnement où ils peuvent librement faire des suggestions.</p>
              <p class="num-text"><span>4)</span>Nous offrons des opportunités d'éducation et de croissance égales en fonction des capacités et des qualifications des employés, afin d'augmenter leur motivation et d'encourager leur développement.</p>
            </div>

            <div>
              <h6>3. Environnement de travail sûr</h6>
              <p class="num-text"><span>1)</span>Nous prenons activement les mesures nécessaires pour la sécurité des employés et nous nous efforçons de maintenir un environnement de travail sûr contre les accidents, les blessures, les catastrophes et les maladies.</p>
              <p class="num-text"><span>2)</span>Nous respectons les lois et les normes relatives à la santé et à la sécurité au travail.</p>
              <p class="num-text"><span>3)</span>Nous nous efforcerons de fournir un environnement de travail dans lequel le travail et la vie des employés sont harmonieusement équilibrés. </p>
