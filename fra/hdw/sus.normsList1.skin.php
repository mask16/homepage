          <div class="susNormsCon susNormsCon06">
            <h5>Chapitre 6 : Contributions à l'État et à la collectivité</h5>
            <div>
              <h6>1. Responsabilité sociale et obligations</h6>
              <p class="num-text"><span>1)</span>Nous contribuons au développement de la société et de l'économie nationale par le respect de diverses lois, l'amélioration de la productivité, la création d'emplois, le paiement honnête des impôts, les cotisations sociales, etc.</p>
              <p class="num-text"><span>2)</span>Nous reconnaissons que nous pouvons assumer notre responsabilité sociale en contribuant au développement social par le biais de diverses activités de service social, telles que des activités de sécurité environnementale et des activités de soutien culturel.</p>
              <p class="num-text"><span>3)</span>Nous contribuons au développement social en exerçant des activités d'entreprise qui respectent les valeurs sociales et ne nous engageons pas dans des activités par des moyens déloyaux tels que la corruption pour des bénéfices commerciaux et l'exploitation des bénéfices des concurrents.</p>
            </div>
            <div>
              <h6>2. Protection de l'environnement</h6>
              <p class="num-text"><span>1)</span>Afin de protéger l'environnement mondial, nous nous conformerons à toutes les réglementations environnementales et réaliserons tous les projets dans le respect de l'environnement.</p>
              <p class="num-text"><span>2)</span>Des efforts doivent être faits pour préserver un environnement propre tout au long du développement, de la production et de l'utilisation de nos produits.</p>
              <p class="num-text"><span>3)</span>Des efforts doivent être faits pour réduire les émissions de gaz à effet de serre en améliorant l'efficacité énergétique.</p>
