            <h5>Chapitre 4 : Éthique de base des employés</h5>
            <div>
              <h6>1. Éthique de base des employés</h6>
              <p class="num-text"><span>1)</span>Les employés partagent la philosophie de gestion de l'entreprise et partagent ses valeurs, et accomplissent fidèlement les tâches assignées individuellement conformément à la politique commerciale de l'entreprise.</p>
              <p class="num-text"><span>2)</span>Les employés créent une culture organisationnelle basée sur une communication fluide et une confiance mutuelle.</p>
              <p class="num-text"><span>3)</span>Les employés ne seront pas discriminés pour quelque raison que ce soit sans rapport avec leurs fonctions, comme le régionalisme, les relations scolaires et la parenté.</p>
              <p class="num-text"><span>4)</span>Les employés doivent immédiatement signaler une violation des principes de gestion éthique au service de gestion de l'éthique.</p>
