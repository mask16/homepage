              <h6>2. Accomplissement de la mission</h6>
              <p class="num-text"><span>1)</span>En tant que fiers membres de la culture d'entreprise de Hyundai Welding (HWBC), les employés maintiendront toujours une attitude honnête et sincère.</p>
              <p class="num-text"><span>2)</span>Les employés doivent contribuer au développement de l'entreprise en démontrant leurs capacités basées sur la créativité.</p>
              <p class="num-text"><span>3)</span>En tant que membres de Hyundai Welding, les employés doivent partager la prospérité avec l'entreprise et exercer leurs fonctions avec la volonté de se développer.</p>
              <p class="num-text"><span>4)</span>Les employés doivent être familiarisés avec les droits et responsabilités donnés et utiliser les valeurs éthiques comme norme pour toutes les actions.</p>
            </div>

            <div>
              <h6>3. Rendement au travail équitable</h6>
              <p class="num-text"><span>1)</span>Les employés doivent préserver leur honneur et leur dignité en tant que membres de Hyundai Welding en s'acquittant de leurs tâches avec honnêteté et intégrité.</p>
              <p class="num-text"><span>2)</span>Les employés doivent exercer leurs fonctions de manière équitable et ne doivent pas se livrer à des actes d'abus d'autorité, de mensonge, d'exagération, etc. pour des intérêts personnels.</p>
