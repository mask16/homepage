            <h5>Chapitre 5 : Ethical Management</h5>
            <div>
              <h6>1. Respect de la loi</h6>
              <p class="num-text"><span>1)</span>Nous exerçons nos activités commerciales de manière équitable et transparente tout en nous conformant aux lois et réglementations en vigueur.</p>
              <p class="num-text"><span>2)</span>Nous nous conformons également à toutes les réglementations internationales telles que l'éthique d'entreprise et commerciale.</p>
            </div>
            <div>
              <h6>2. Commerce équitable</h6>
              <p class="num-text"><span>1)</span>Toutes les transactions avec nos clients seront transparentes et nous n'imposerons pas d'actes déloyaux ou d'influence en utilisant la position supérieure de l'entreprise.</p>
              <p class="num-text"><span>2)</span>Tous les clients se verront garantir une opportunité équitable, et la sélection de nos clients sera déterminée par des normes et des procédures objectives et équitables.</p>
              <p class="num-text"><span>3)</span>Lors de la participation à un appel d'offres, les informations des concurrents ne seront pas fournies à d'autres sociétés.</p>
              <p class="num-text"><span>4)</span>Lorsque nous traitons avec des clients, nous nous conformerons aux lois, réglementations et systèmes pertinents.</p>
              <p class="num-text"><span>5)</span>Toutes les transactions avec les clients doivent être effectuées équitablement et à des conditions égales, et les conditions et procédures doivent être pleinement discutées à l'avance.</p>
