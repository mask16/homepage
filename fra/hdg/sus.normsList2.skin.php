          <div class="susNormsCon susNormsCon04">
            <h5>Chapitre 4 : Culture organisationnelle saine</h5>
            <div>
              <h6>1. Respect mutuel des employés</h6>
              <p class="num-text"><span>1)</span>Les employés doivent se respecter les uns les autres et avoir de bonnes manières pour la vie professionnelle.</p>
              <p class="num-text"><span>2)</span>Les employés ne doivent pas se discriminer pour des raisons liées au sexe, à la religion, à l'âge, à l'origine, à la formation ou à d'autres raisons.</p>
              <p class="num-text"><span>3)</span>Les employés ne doivent pas s'engager dans des activités non officielles telles que la création de factions et la promotion de la discorde sociale.</p>
              <p class="num-text"><span>4)</span>Les employés ne doivent pas restreindre, exclure, séparer ou discriminer des collègues handicapés sans raisons justifiables.</p>
            </div>

            <div>
              <h6>2. Responsabilité des cadres et chefs de service</h6>
              <p class="num-text"><span>1)</span>Les cadres et les chefs de service doivent donner le bon exemple aux membres du service en se conformant au code d'éthique et à ses pratiques par une prise de décision et des actions équitables.</p>
              <p class="num-text"><span>2)</span>Les cadres et les chefs de service doivent fournir des conseils de temps à autre afin que tous les membres du service puissent pleinement comprendre le Code d'éthique et ses pratiques, et prendre les précautions appropriées pour prévenir les comportements contraires à l'éthique.</p>
            </div>


            <div>
              <h6>3. Responsabilité des membres du département</h6>
              <p class="num-text"><span>1)</span>Lorsqu'un membre du département se voit confier un travail qui n'est pas clair en vertu des règlements de l'entreprise, il doit demander au chef de département ou à l'exécutif avant de continuer.</p>
              <p class="num-text"><span>2)</span>Si un membre du département se voit confier un travail illégal ou injuste par son gestionnaire, il ne doit pas le poursuivre inconditionnellement.</p>
              <p class="num-text"><span>3)</span>Un membre du service doit refuser les ordres injustes de son gestionnaire en présentant des preuves. Si le gestionnaire donne encore des ordres injustes, ils doivent être signalés au Service de gestion de l'éthique.</p>
            </div>

            <div>
              <h6>4. Intimidation et harcèlement sexuel en milieu de travail</h6>
              <p>Des mesures disciplinaires sévères, telles que la suspension, la rétrogradation, l'inscription sur la liste d'attente, le licenciement, etc. peuvent être imposées aux employés qui ont causé de l'intimidation ou du harcèlement sexuel au travail. Des transferts de personnel peuvent également être effectués pour éviter qu'ils travaillent au même endroit que la victime.</p>
              <p class="num-text"><span>1)</span>Intimidation<br />
                - Les instructions de travail inutiles ne devraient pas être faites avant ou après les heures de bureau et ne devraient pas violer la semaine de travail de 52 heures.<br />
				- Les employés ne doivent pas intentionnellement ostraciser ou diffuser de fausses informations sur leurs collègues dans les médias sociaux ou le babillard.<br />
				- Les managers ne doivent pas utiliser un langage vulgaire ou insulter leurs employés même si leurs performances sont médiocres. Les managers ne peuvent pas forcer leurs employés à participer à des dîners d'entreprise, à faire des courses ou à rédiger des rapports sans rapport avec le travail.<br />
				- Un seul employé ne doit pas être affecté à plusieurs reprises à un travail difficile que tous les autres employés sont réticents à faire, à moins que cela ne soit spécifié dans leur contrat de travail.<br />
				- Un employé ne doit pas être intentionnellement exclu des informations importantes ou de la prise de décision liée au travail sans raisons justifiables.<br />
				Les employés ne doivent pas être traités injustement par leurs gestionnaires, par l'utilisation d'autorités telles que le changement, l'exclusion et le transfert de tâches.
              </p>
              <p class="num-text"><span>2)</span>Harcèlement sexuel en milieu de travail<br />
                - Les employés ne doivent se livrer à aucun acte qui amène un collègue à ressentir une humiliation, un dégoût ou une pression sexuelle.<br />
Il est interdit aux employés de faire des blagues obscènes, des commérages, des contacts physiques ou de forcer des personnes à verser de l'alcool ou à danser lors de dîners d'entreprise.
- Les employés ne doivent pas intentionnellement exposer ou toucher des parties sensibles du corps d'un collègue, ou forcer des collègues à voir des photographies et des images obscènes.<br />
- Les employés ne doivent pas évaluer sexuellement le corps ou la silhouette des autres.<br />
- Un refus de harcèlement sexuel doit être respecté, et aucun désavantage ne doit être accordé dans de tels cas.<br />
- Les employés ne peuvent pas conclure d'accords concernant des demandes sexuelles et ne peuvent pas forcer des réunions, des relations amoureuses ou des contacts physiques.<br />
              </p>
            </div>

            <div>
              <h6>5. Jouer et boire</h6>
              <p class="num-text"><span>1)</span>Les employés ne peuvent pas forcer leurs collègues à acheter des garanties, des produits financiers (assurances, etc.) ou d'autres biens.</p>
              <p class="num-text"><span>2)</span>Les employés ne doivent pas s'engager dans des activités de jeu, et dans le cas où un employé gagne de l'argent ou des objets de valeur grâce au jeu, cela sera considéré comme de la corruption.</p>
              <p class="num-text"><span>3)</span>Les employés ne doivent pas être affectés par l'alcool pendant les heures de travail. Cependant, de tels cas sont tolérés en cas d'approbation préalable pour l'accueil et le parrainage d'événements.</p>
              <p class="num-text"><span>4)</span>Les employés ne doivent pas travailler sous l'influence de l'alcool.</p>
              <p class="num-text"><span>5)</span>Les employés ne peuvent pas conduire sous l'influence de l'alcool pour le travail, et des mesures disciplinaires sévères telles que le licenciement peuvent être imposées si elles sont détectées. Toutefois, si un salarié boit inévitablement de l'alcool lors d'un rendez-vous avec un client, un congé peut être accordé le lendemain conformément au règlement de l'entreprise.</p>
            </div>
          </div>

          <div class="susNormsCon susNormsCon05">
            <h5>Chapitre 5 : Protection des informations, gestion de la sécurité, etc.</h5>
            <div>
              <h6>1. Protection des informations</h6>
              <p class="num-text"><span>1)</span>Les employés doivent protéger la propriété physique, la propriété intellectuelle et les secrets commerciaux de l'entreprise. Ils ne peuvent divulguer des informations internes à des tiers sans l'accord préalable de la société.</p>
              <p class="num-text"><span>2)</span>Les employés ne peuvent pas divulguer les règlements commerciaux de l'entreprise avec l'approbation préalable de l'entreprise.</p>
              <p class="num-text"><span>3)</span>Le système d'information de la société ne doit être utilisé qu'à des fins commerciales et ne doit pas être utilisé pour des intérêts personnels.</p>
            </div>

            <div>
              <h6>2. Gestion de la sécurité</h6>
              <p class="num-text"><span>1)</span>Les données du système d'information de l'entreprise ne doivent pas être falsifiées, falsifiées ou endommagées sans autorisation.</p>
              <p class="num-text"><span>2)</span>L'identifiant et le mot de passe fournis par la société ne doivent pas être partagés avec d'autres. Cependant, il peut être temporairement partagé à des fins professionnelles inévitables.</p>
              <p class="num-text"><span>3)</span>Il est interdit aux employés de tenter d'identifier les identifiants et les mots de passe d'autres personnes, et les informations non autorisées ne peuvent pas être consultées.</p>
              <p class="num-text"><span>4)</span>Les données susceptibles de porter atteinte au droit d'auteur ne peuvent être diffusées sans autorisation au sein de l'entreprise.</p>
              <p class="num-text"><span>5)</span>Les employés doivent utiliser un logiciel acheté, et toute responsabilité pour l'utilisation de logiciels illégaux incombera aux employés concernés.</p>
            </div>

            <div>
              <h6>3. Confidentialité</h6>
              <p class="num-text"><span>1)</span>Les employés ne doivent pas divulguer intentionnellement les informations personnelles des employés et des parties prenantes.</p>
              <p class="num-text"><span>2)</span>Les processeurs d'informations personnelles doivent gérer la confidentialité afin qu'elle ne soit pas endommagée ou perdue.</p>
              <p class="num-text"><span>3)</span>Afin d'assurer la sécurité de la vie privée, les documents contenant des informations personnelles et les supports de stockage auxiliaires doivent être stockés dans un endroit verrouillé.</p>
              <p class="num-text"><span>4)</span>Afin d'éviter les fuites d'informations personnelles, l'entreprise doit fournir une formation aux processeurs d'informations personnelles.</p>
            </div>

