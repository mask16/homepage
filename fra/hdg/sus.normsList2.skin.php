          <div class="susNormsCon susNormsCon03">
            <h5>Chapitre 3 : Culture d'entreprise propre</h5>
            <div>
              <h6>1. Détournements et détournements de fonds publics</h6>
              <p class="num-text"><span>1)</span>Les employés ne peuvent utiliser les fonds publics de l'entreprise à des fins personnelles pour quelque raison que ce soit. Lorsqu'elles sont détectées, des accusations criminelles peuvent être déposées en fonction du montant et de la perte.</p>
              <p class="num-text"><span>2)</span>Les fonds publics de l'entreprise sont gérés par un compte d'entreprise et toutes les dépenses doivent être dûment justifiées.</p>
            </div>

            <div>
              <h6>2. Mauvaise exécution du budget</h6>
              <p class="num-text"><span>1)</span>Les employés doivent s'abstenir de gaspiller le budget en raison d'une utilisation inutile ou d'une exécution excessive, et doivent s'assurer que tous les budgets sont exécutés de manière raisonnable et efficace.</p>
              <p class="num-text"><span>2)</span>Les employés ne doivent pas utiliser le budget des ventes à des fins autres que les dîners de service, l'argent de félicitations pour les employés et l'achat d'articles personnels.</p>
              <p class="num-text"><span>3)</span>Les employés ne peuvent pas utiliser les cartes de crédit d'entreprise à des fins qui ne sont pas liées aux affaires.</p>
              <p class="num-text"><span>4)</span>Les employés ne peuvent pas facturer les dépenses de l'entreprise utilisées à des fins non professionnelles.</p>
              <p class="num-text"><span>5)</span>Si les employés utilisent le budget de l'entreprise à des fins non commerciales et ne le signalent pas au service de gestion de l'éthique, les personnes concernées et les employés du service qui en ont connaissance peuvent faire l'objet de mesures disciplinaires. </p>
            </div>

            <div>
              <h6>3. Usage privé et dommages aux biens de l'entreprise</h6>
              <p class="num-text"><span>1)</span>Les actifs de l'entreprise, tels que la propriété physique, les droits de propriété intellectuelle et les secrets commerciaux de l'entreprise, ne peuvent pas être utilisés à des fins personnelles.</p>
              <p class="num-text"><span>2)</span>Si un salarié souhaite céder ou prêter les biens de l'entreprise à lui-même ou à un tiers, il doit obtenir l'approbation du chef de service et du cadre responsable et suivre les procédures prescrites.</p>
              <p class="num-text"><span>3)</span>Les employés ne peuvent pas utiliser l'ordinateur ou l'ordinateur portable de l'entreprise pour effectuer des opérations sur actions personnelles, des jeux d'argent, des vidéos illégales et d'autres sites sans rapport avec les affaires.</p>
              <p class="num-text"><span>4)</span>Les employés ne doivent pas endommager intentionnellement les actifs de l'entreprise. Si un employé le fait, l'entreprise peut le tenir pour responsable.</p>
            </div>

            <div>
              <h6>4. Acceptation de la corruption</h6>
              <p class="num-text"><span>1)</span>Les employés ne doivent pas chercher d'argent, de divertissement ou de commodité auprès des parties intéressées en abusant de leurs positions supérieures, et ne doivent pas s'engager dans des transactions financières avec des collègues.</p>
