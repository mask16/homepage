          <div class="susNormsCon susNormsCon02">
            <h5>Chapitre 2 : Exécution juste et véridique des devoirs</h5>
            <div>
              <h6>1. Préparation et gestion des informations et documents clés</h6>
              <p class="num-text"><span>1)</span>Les employés ne doivent pas utiliser les informations acquises dans l'entreprise à des fins personnelles ou les divulguer à des tiers.</p>
              <p class="num-text"><span>2)</span>Les employés ne doivent pas négocier d'actions en utilisant des informations internes et ne doivent pas fournir d'informations confidentielles à des tiers susceptibles d'affecter les cours des actions sans procédure régulière.</p>
              <p class="num-text"><span>3)</span>Les employés doivent préparer les documents pour les affaires conformément aux règlements de l'entreprise et doivent immédiatement signaler et modifier les documents en cas d'erreur.</p>
            </div>

            <div>
              <h6>2.  Demande de poste</h6>
              <p class="num-text"><span>1)</span>Les employés ne doivent pas faire de demandes déraisonnables à l'entreprise et à ses entreprises intéressées en utilisant leur statut, comme demander l'emploi de membres de la famille, de parents ou de connaissances.</p>
              <p class="num-text"><span>2)</span>Les employés ne doivent pas demander à l'équipe des RH des évaluations de personnel injustes en utilisant leur statut.</p>
              <p class="num-text"><span>3)</span>Les employés ne doivent demander à aucune autre personne de faire une demande à l'équipe des RH pour une influence déloyale sur leur nomination, promotion, transfert, etc.</p>
              <p class="num-text"><span>4)</span>Les employés ne recevront aucune garantie d'emploi après la retraite de la part des intéressés.</p>
              <p class="num-text"><span>5)</span>Si un employé reçoit une demande de personnel, il doit l'informer qu'il s'agit d'une demande illégale et indiquer clairement son intention de refus.</p>
            </div>

            <div>
              <h6>3. Interdiction des emplois multiples et des postes simultanés</h6>
              <p class="num-text"><span>1)</span>Il est interdit aux employés de travailler en double dans d'autres entreprises sans l'approbation préalable de l'entreprise.</p>
              <p class="num-text"><span>2)</span>Les employés ne peuvent pas exercer simultanément les fonctions d'autres entreprises sans l'autorisation de l'entreprise.</p>
            </div>

            <div>
              <h6>4. Signature de contrats avec des partenaires</h6>
              <p class="num-text"><span>1)</span>Les employés doivent exercer leurs fonctions de manière équitable et transparente conformément aux procédures prescrites par les lois et règlements pertinents pour les appels d'offres, les contrats et l'exécution des contrats menés par l'entreprise.</p>
              <p class="num-text"><span>2)</span>Lors de la sélection d'un sous-traitant, toutes les entreprises dûment qualifiées se verront accorder des chances égales de transaction et de libre concurrence, et seront sélectionnées selon des procédures d'évaluation transparentes.</p>
              <p class="num-text"><span>3)</span>En principe, les commandes doivent être passées par appel d'offres, mais les contrats privés peuvent être sélectionnés selon une procédure régulière conformément aux besoins et aux réglementations de l'entreprise.</p>
              <p class="num-text"><span>4)</span>Les employés ne recevront aucune forme d'avantages économiques ou non économiques de la part de sous-traitants utilisant leur statut supérieur.</p>
              <p class="num-text"><span>5)</span>Les employés doivent être pleinement conscients des procédures de base pour la signature des contrats et ne doivent pas conclure de contrats de construction, de services, etc. à un prix supérieur au prix du marché.</p>
              <p class="num-text"><span>6)</span>Les employés doivent s'efforcer de ne pas avoir de conflits d'intérêts lors de la signature de contrats avec des sous-traitants. En cas de conflit d'intérêts avec l'entreprise, ils le signalent immédiatement à la Direction de la gestion de l'éthique.</p>
            </div>
