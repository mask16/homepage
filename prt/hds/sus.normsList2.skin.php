            <h5>Capítulo 5 : Proteção de informações, gerenciamento de segurança, etc.</h5>
            <div>
              <h6>1. Proteção de Informação</h6>
              <p class="num-text"><span>1)</span>Os funcionários devem proteger a propriedade física, propriedade intelectual e segredos comerciais da empresa. Eles não podem divulgar informações internas a terceiros sem a aprovação prévia da empresa.</p>
              <p class="num-text"><span>2)</span>Os funcionários não podem divulgar os regulamentos de negócios da empresa com a aprovação prévia da empresa.</p>
