              <p class="num-text"><span>2)</span>Os funcionários não devem se envolver em atividades de jogos de azar e, caso um funcionário ganhe dinheiro ou objetos de valor com jogos de azar, isso será considerado suborno.</p>
              <p class="num-text"><span>3)</span>Os funcionários não devem ser afetados pelo álcool durante o horário de trabalho. No entanto, tais casos são tolerados em caso de aprovação prévia para hospedagem e patrocínio de eventos.</p>
              <p class="num-text"><span>4)</span>Os funcionários não devem trabalhar sob a influência de álcool.</p>
