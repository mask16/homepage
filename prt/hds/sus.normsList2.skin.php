            <h5>Capítulo 4 : Cultura Organizacional Saudável</h5>
            <div>
              <h6>1.  Respeito mútuo pelos funcionários</h6>
              <p class="num-text"><span>1)</span>Os funcionários devem respeitar uns aos outros e ter boas maneiras na vida profissional.</p>
              <p class="num-text"><span>2)</span>Os funcionários não devem se discriminar por motivos de gênero, religião, idade, origem, escolaridade ou outros motivos.</p>
              <p class="num-text"><span>3)</span>Os funcionários não devem se envolver em atividades não oficiais, como criar facções e promover desarmonia social.</p>
              <p class="num-text"><span>4)</span>Os funcionários não devem restringir, excluir, separar ou discriminar colegas com deficiência sem motivos justificáveis.</p>
            </div>

            <div>
              <h6>2. Responsabilidade dos Executivos e Chefes de Departamento</h6>
              <p class="num-text"><span>1)</span>Os executivos e chefes de departamento devem dar um bom exemplo aos membros do departamento, cumprindo o Código de Ética e suas práticas por meio de decisões e ações justas.</p>
              <p class="num-text"><span>2)</span>Os executivos e chefes de departamento devem fornecer aconselhamento de tempos em tempos para que todos os membros do departamento possam compreender totalmente o Código de Ética e suas práticas e tomar as precauções adequadas para evitar comportamentos antiéticos.</p>
            </div>


            <div>
              <h6>3. Responsabilidade dos membros do departamento</h6>
              <p class="num-text"><span>1)</span>Quando um membro do departamento recebe um trabalho que não está claro de acordo com os regulamentos da empresa, ele deve perguntar ao chefe do departamento ou executivo antes de prosseguir.</p>
              <p class="num-text"><span>2)</span>Se um membro do departamento receber trabalho ilegal ou injusto de seu gerente, ele não deve prosseguir com isso incondicionalmente.</p>
              <p class="num-text"><span>3)</span>Um membro do departamento deve recusar ordens injustas de seu gerente, apresentando provas. Se o gerente ainda der ordens injustas, elas devem ser relatadas ao Departamento de Gestão de Ética.</p>
            </div>

            <div>
              <h6>4. Bullying e assédio sexual no local de trabalho</h6>
              <p>Fortes ações disciplinares, como suspensão, rebaixamento, colocação na lista de espera, demissão, etc. podem ser impostas aos funcionários que tenham causado bullying ou assédio sexual no local de trabalho. As transferências de pessoal também podem ser realizadas para impedir que trabalhem no mesmo local que a vítima.</p>
              <p class="num-text"><span>1)</span>Bullying<br />
                - O colaborador não deve praticar atos alheios às suas funções que causem dor física e psíquica, ou que agravem o ambiente de trabalho pelo uso de posição superior na empresa.<br />
                - Instruções de trabalho desnecessárias não devem ser feitas antes ou depois do horário comercial e não devem violar a semana de trabalho de 52 horas.<br />
                - Os funcionários não devem intencionalmente ostracizar ou espalhar informações falsas de seus colegas nas redes sociais ou no quadro de avisos.<br />
                -  Os gerentes não devem usar linguagem vulgar ou insultar seus funcionários, mesmo que seu desempenho seja ruim..<br />
                - Os gerentes não podem forçar seus funcionários a participar de jantares da empresa, fazer recados ou escrever relatórios não relacionados ao trabalho.<br />
                -Um único funcionário não deve ser repetidamente designado para trabalho duro que todos os outros funcionários estejam relutantes em fazer, a menos que especificado em seu contrato de trabalho.<br/>
                - Um funcionário não deve ser excluído intencionalmente de informações importantes ou da tomada de decisões relacionadas ao trabalho sem motivos justificáveis.<br/>
                - Os funcionários não devem ser tratados injustamente por seus gerentes, por meio do uso de autoridade, como mudança, exclusão e transferência de funções.
