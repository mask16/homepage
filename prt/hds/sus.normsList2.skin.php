            <div>
              <h6>2. Gestão de Segurança</h6>
              <p class="num-text"><span>1)</span>Os dados do sistema de informação da empresa não devem ser falsificados, adulterados ou danificados sem autorização.</p>
              <p class="num-text"><span>2)</span>O ID e senha fornecidos pela empresa não devem ser compartilhados com outras pessoas. No entanto, pode ser temporariamente compartilhado para fins de trabalho inevitáveis.</p>
              <p class="num-text"><span>3)</span>Os funcionários estão proibidos de tentar identificar IDs e senhas de outras pessoas, e informações não autorizadas não podem ser acessadas.</p>
              <p class="num-text"><span>4)</span>Dados que podem infringir direitos autorais não podem ser distribuídos sem permissão dentro da empresa.</p>
              <p class="num-text"><span>5)</span>Os funcionários devem usar um programa de software adquirido e toda a responsabilidade pelo uso de software ilegal deve ser assumida pelos funcionários em questão.</p>
            </div>

            <div>
              <h6>3. Privacidade</h6>
              <p class="num-text"><span>1)</span>Os funcionários não podem divulgar intencionalmente informações pessoais de funcionários e partes interessadas.</p>
              <p class="num-text"><span>2)</span>Os processadores de informações pessoais devem gerenciar a privacidade para que ela não seja danificada ou perdida.</p>
              <p class="num-text"><span>3)</span>Para garantir a segurança da privacidade, os documentos que contenham informações pessoais e meios auxiliares de armazenamento deverão ser armazenados em local trancado.</p>
              <p class="num-text"><span>4)</span>Para evitar o vazamento de informações pessoais, a empresa deve fornecer educação para os processadores de informações pessoais.</p>
