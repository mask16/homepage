              <p class="num-text"><span>2)</span>Assédio Sexual no Local de Trabalho<br />
                - Os funcionários não devem se envolver em nenhum ato que faça com que um colega sinta humilhação, nojo ou pressão sexual.<br />
                - Os funcionários estão proibidos de fazer piadas obscenas, fofocar, contato físico ou forçar as pessoas a derramar álcool ou dançar em jantares de empresa.<br />
                - Os funcionários não podem expor intencionalmente ou tocar partes sensíveis do corpo de um colega, ou forçar os colegas a ver fotos e imagens obscenas.<br />
                - Os funcionários não podem avaliar sexualmente os corpos ou figuras uns dos outros.<br />
                - A recusa do assédio sexual deve ser respeitada, e nenhuma desvantagem deve ser dada em tais casos.<br/>
                - Os funcionários não podem fazer negócios relativos a demandas sexuais e não podem forçar reuniões, relacionamentos românticos ou contato físico.
              </p>
